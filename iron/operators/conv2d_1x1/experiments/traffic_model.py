#!/usr/bin/env python3
"""DRAM traffic model for the conv2d_1x1_opt design -- and its verification.

The roofline needs one number per layer that the throughput plots never needed:
how many bytes actually cross the DRAM boundary. That is *not* the tensor
footprint. Under the design's tiling each operand is re-fetched:

  * A is re-read once per column-block pass   -> N/(n * cols) times
  * B is re-read once per row-block pass      -> M/(m * 4)    times
  * C is written exactly once

so, in elements of the padded problem,

  A_elems = M*K * N/(n*cols)      B_elems = K*N * M/(m*4)      C_elems = M*N

This module derives those counts from the runtime sequence in design.py, and
`verify()` checks them against the design's OWN TensorAccessSequence taps
(generate_taps=True), which are generated by the same code that emits the
npu_dma_memcpy_nd ops. If the model and the taps ever disagree, the model is
wrong -- the taps are the ground truth.

Import surface: `traffic(...)` and `layer_point(...)`, used by roofline.py.
"""
import pathlib
import sys

HERE = pathlib.Path(__file__).parent
N_AIE_ROWS = 4
BYTES_BF16 = 2


def ceildiv(a, b):
    return -(a // -b)


def traffic(M, K, N, m, k, n, cols, itemsize=BYTES_BF16):
    """Bytes crossing the DRAM boundary for one dispatch of the padded problem.

    M, K, N are the *design* dims (already padded, and already swapped if the
    cols->M swap is engaged): M = rows operand extent, N = cols operand extent.
    """
    n_col_passes = N // (n * cols)  # times A is re-fetched
    n_row_passes = M // (m * N_AIE_ROWS)  # times B is re-fetched
    a_elems = M * K * n_col_passes
    b_elems = K * N * n_row_passes
    c_elems = M * N
    return {
        "A_bytes": a_elems * itemsize,
        "B_bytes": b_elems * itemsize,
        "C_bytes": c_elems * itemsize,
        "total_bytes": (a_elems + b_elems + c_elems) * itemsize,
        "A_refetch": n_col_passes,
        "B_refetch": n_row_passes,
    }


def layer_point(op, C_in, C_out, pixels, sec):
    """One roofline point for a measured run of `op` (an instantiated Conv2d1x1).

    Arithmetic intensity is USEFUL flops over ACTUAL bytes -- the same
    convention the throughput plots use for GF/s (padding is overhead, never
    credit), so a point's x and y are consistent with each other and with the
    rest of the deck.
    """
    t = traffic(op.M, op.K, op.N, op.tile_m, op.tile_k, op.tile_n,
                op.num_aie_columns)
    useful_flops = 2.0 * C_in * C_out * pixels
    return {
        "ai": useful_flops / t["total_bytes"],
        "gf": useful_flops / sec / 1e9,
        "bytes": t["total_bytes"],
        "gbps": t["total_bytes"] / sec / 1e9,
        "useful_flops": useful_flops,
        "A_refetch": t["A_refetch"],
        "B_refetch": t["B_refetch"],
        "A_bytes": t["A_bytes"],
        "B_bytes": t["B_bytes"],
        "C_bytes": t["C_bytes"],
    }


# ---------------------------------------------------------------------------
# Verification against the design's own taps
# ---------------------------------------------------------------------------
def _tap_bytes(seq, itemsize=BYTES_BF16):
    """Total elements described by a TensorAccessSequence, counting repeats.

    A tap's sizes/strides describe one npu_dma_memcpy_nd; a size with stride 0
    is a *repeat* of the same data, which still costs DRAM reads, so it counts.
    """
    total = 0
    for tap in seq:
        prod = 1
        for s in tap.sizes:
            prod *= s
        total += prod
    return total * itemsize


def verify(cases=None):
    """Check `traffic()` against the taps design.py records for its own DMAs.

    One caveat, and it is the design's, not the model's: `A_taps.append` sits
    OUTSIDE the `if col < n_aie_rows` guard that gates the actual `rt.fill` for
    A (design.py, "A input transfer"). So at cols=8 the tap list records 8
    appends per row-pass where only 4 DMAs are issued, and A's tap total comes
    out 2x the traffic. The taps are explicitly recording-only ("This line does
    not change MLIR output at all"), so the emitted program is unaffected -- but
    it means the exact check has to run at cols<=4, where the guard is a no-op
    and every append corresponds to a real fill. We do both: exact at cols=4,
    and at cols=8 we assert the A ratio is exactly n_aie_rows/cols.
    """
    sys.path.insert(0, str(HERE.parent.parent.parent.parent))
    from iron.operators.conv2d_1x1_opt.design import my_matmul

    if cases is None:
        #    M     K     N    m   k    n  cols  a_cm b_cm c_cm
        cases = [
            # cols=4: taps are exact, so these validate the formula itself.
            (3072, 768, 256, 16, 64, 64, 4, 0, 0, 0),   # plain, headline layer
            (64, 768, 3072, 16, 64, 64, 4, 1, 1, 1),    # swapped, headline layer
            (2048, 1024, 256, 16, 64, 64, 4, 0, 0, 0),  # plain, ResNeXt expand
            (1536, 384, 256, 16, 64, 64, 4, 0, 0, 0),   # plain, N=196 -> 256
            (256, 384, 1536, 16, 64, 64, 4, 1, 1, 1),   # swapped, N=196
            (512, 1024, 1024, 16, 64, 128, 4, 0, 0, 0),  # plain, n=128 tile
            (1024, 512, 512, 32, 128, 64, 4, 0, 0, 0),  # plain, m=32 k=128 tile
            # cols=8: production config. A is expected 2x by the tap artifact.
            (3072, 768, 512, 16, 64, 64, 8, 0, 0, 0),
            (64, 768, 3072, 16, 64, 64, 8, 1, 1, 1),
            (2048, 1024, 512, 16, 64, 64, 8, 0, 0, 0),
            (1024, 512, 1024, 16, 64, 128, 8, 0, 0, 0),
        ]

    ok = True
    for M, K, N, m, k, n, cols, a_cm, b_cm, c_cm in cases:
        A_seq, B_seq, C_seq = my_matmul(
            dev="npu2", M=M, K=K, N=N, m=m, k=k, n=n, n_aie_cols=cols,
            dtype_in_str="bf16", dtype_out_str="bf16",
            b_col_maj=b_cm, c_col_maj=c_cm, a_col_maj=a_cm,
            use_scalar=False, emulate_bf16_mmul_with_bfp16=False,
            prio_accuracy=True, separate_c_tiles=0, trace_size=0,
            generate_taps=True,
        )
        model = traffic(M, K, N, m, k, n, cols)
        meas = {
            "A_bytes": _tap_bytes(A_seq),
            "B_bytes": _tap_bytes(B_seq),
            "C_bytes": _tap_bytes(C_seq),
        }
        meas["total_bytes"] = sum(meas.values())
        # Expected A over-count from the tap-recording artifact described above.
        a_factor = max(1, cols // N_AIE_ROWS)
        expect = dict(model)
        expect["A_bytes"] = model["A_bytes"] * a_factor
        expect["total_bytes"] = expect["A_bytes"] + model["B_bytes"] + model["C_bytes"]

        tag = (f"M={M:5d} K={K:5d} N={N:5d} tile={m}/{k}/{n} cols={cols} "
               f"swap={a_cm}" + ("   [A taps x2 by design artifact]" if a_factor > 1 else ""))
        match = all(expect[key] == meas[key] for key in meas)
        ok &= match
        print(f"{'OK  ' if match else 'FAIL'} {tag}")
        for key in ("A_bytes", "B_bytes", "C_bytes", "total_bytes"):
            flag = "" if expect[key] == meas[key] else "   <-- MISMATCH"
            print(f"       {key:12s} model {model[key]:12,d}   taps {meas[key]:12,d}{flag}")
    print("\nALL MATCH" if ok else "\nMODEL DISAGREES WITH TAPS")
    return ok


if __name__ == "__main__":
    sys.exit(0 if verify() else 1)
